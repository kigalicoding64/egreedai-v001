import JSZip from 'jszip';
import { saveAs } from 'file-saver';
import { BuilderComponent } from '@/types/builder';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { BuilderPage } from '@/lib/BuilderPage';
import builderPageSource from '@/lib/BuilderPage.tsx?raw';
import builderStylesSource from '@/lib/builderPageStyles.ts?raw';

const escapeHTML = (value: string) => value.replace(/[&<>"']/g, char => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[char] || char));

export function exportHTMLCode(components: BuilderComponent[], pageName: string): string {
  const markup = renderToStaticMarkup(React.createElement(BuilderPage, { sections: components }));
  return `<!DOCTYPE html><html lang="en"><head><meta charset="UTF-8"><meta name="viewport" content="width=device-width, initial-scale=1.0"><title>${escapeHTML(pageName)}</title><meta name="description" content="${escapeHTML(pageName)} — built with EgreedAI"><style>body{margin:0}html{scroll-behavior:smooth}</style></head><body>${markup}</body></html>`;
}

export function exportReactCode(components: BuilderComponent[], pageName: string): string {
  const name = pageName.replace(/[^a-zA-Z]/g, '') || 'Page';
  return `import { BuilderPage, type PageSection } from './BuilderPage';
const sections: PageSection[] = ${JSON.stringify(components, null, 2)};
export default function ${name}Page() { return <BuilderPage sections={sections} />; }
`;
}

export async function exportAsZip(htmlCode: string, reactCode: string, pageName: string) {
  const zip = new JSZip();

  // HTML version
  zip.file('index.html', htmlCode);

  // Extract CSS
  const cssMatch = htmlCode.match(/<style>([\s\S]*?)<\/style>/);
  if (cssMatch) {
    zip.file('styles.css', cssMatch[1].trim());
  }

  // React + Vite + Tailwind project, runnable with `npm install && npm run dev`
  const comp = pageName.replace(/[^a-zA-Z]/g, '') || 'Page';
  const r = zip.folder('react');
  r?.file('package.json', JSON.stringify({
    name: pageName.toLowerCase().replace(/[^a-z0-9-]/g, '-') || 'egreed-page',
    private: true, version: '1.0.0', type: 'module',
    scripts: { dev: 'vite', build: 'tsc -b && vite build', preview: 'vite preview' },
    dependencies: { react: '^18.3.1', 'react-dom': '^18.3.1' },
    devDependencies: {
      '@types/react': '^18.3.3', '@types/react-dom': '^18.3.0', '@vitejs/plugin-react': '^4.3.1',
      autoprefixer: '^10.4.19', postcss: '^8.4.38', tailwindcss: '^3.4.4', typescript: '^5.5.3', vite: '^5.4.0',
    },
  }, null, 2));
  r?.file('index.html', `<!doctype html>\n<html lang="en">\n  <head>\n    <meta charset="UTF-8" />\n    <meta name="viewport" content="width=device-width, initial-scale=1.0" />\n    <title>${escapeHTML(pageName)}</title>\n    <meta name="description" content="${escapeHTML(pageName)} — built with EgreedAI" />\n  </head>\n  <body>\n    <div id="root"></div>\n    <script type="module" src="/src/main.tsx"></script>\n  </body>\n</html>\n`);
  r?.file('vite.config.ts', `import { defineConfig } from 'vite';\nimport react from '@vitejs/plugin-react';\nimport path from 'path';\n\nexport default defineConfig({\n  plugins: [react()],\n  resolve: { alias: { '@': path.resolve(__dirname, './src') } },\n});\n`);
  r?.file('tailwind.config.js', `/** @type {import('tailwindcss').Config} */\nexport default {\n  content: ['./index.html', './src/**/*.{ts,tsx}'],\n  theme: { container: { center: true, padding: '1rem' }, extend: {} },\n  plugins: [],\n};\n`);
  r?.file('postcss.config.js', `export default { plugins: { tailwindcss: {}, autoprefixer: {} } };\n`);
  r?.file('tsconfig.json', JSON.stringify({
    compilerOptions: {
      target: 'ES2020', lib: ['ES2020', 'DOM', 'DOM.Iterable'], module: 'ESNext', moduleResolution: 'bundler',
      jsx: 'react-jsx', esModuleInterop: true, strict: true, skipLibCheck: true, noEmit: true, isolatedModules: true,
      baseUrl: '.', paths: { '@/*': ['./src/*'] },
    },
    include: ['src'],
  }, null, 2));
  r?.file('src/index.css', '@tailwind base;\n@tailwind components;\n@tailwind utilities;\n');
  r?.file('src/main.tsx', `import { StrictMode } from 'react';\nimport { createRoot } from 'react-dom/client';\nimport ${comp}Page from './Page';\nimport './index.css';\n\nconst root = document.getElementById('root');\nif (root) createRoot(root).render(\n  <StrictMode>\n    <${comp}Page />\n  </StrictMode>,\n);\n`);
  r?.file('src/Page.tsx', reactCode);
  r?.file('src/BuilderPage.tsx', builderPageSource);
  r?.file('src/builderPageStyles.ts', builderStylesSource);
  r?.file('README.md', `# ${pageName}\n\nGenerated by EgreedAI Builder (React + Tailwind CSS + Vite).\n\n## Setup\n\n\`\`\`bash\nnpm install\nnpm run dev\n\`\`\`\n`);

  const blob = await zip.generateAsync({ type: 'blob' });
  saveAs(blob, `${pageName.toLowerCase()}.zip`);
}
